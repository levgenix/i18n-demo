package com.example.i18n;

/**
 * Сервис ядра интернационализации (v2), отвечающий за разрешение переводов на основе контекста запроса.
 */
public interface TranslationService {

    /**
     * Возвращает значение перевода по полному ключу/мнемонике для языка текущего пользователя.
     * <p>
     * Язык автоматически извлекается из контекста текущего запроса/потока (Spring {@code LocaleContextHolder}).
     * </p>
     * 
     * @param mnemonic полный ключ мнемоники (включая префиксы)
     * @return локализованное значение или fallback-строка
     */
    String localize(String mnemonic);

    /**
     * Возвращает значение перевода по полному ключу/мнемонике строго для языка по умолчанию (default/fallback),
     * игнорируя текущий язык пользователя из контекста.
     * 
     * @param mnemonic полный ключ мнемоники (включая префиксы)
     * @return строка перевода для системного языка по умолчанию
     */
    default String localizeDefault(String mnemonic) {
        return localize(mnemonic);
    }
}
