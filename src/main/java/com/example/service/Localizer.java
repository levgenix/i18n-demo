package com.example.service;

/**
 * Базовый контракт для получения локализованных строк и дефолтных текстов.
 */
@FunctionalInterface
public interface Localizer {

    /**
     * Возвращает локализованную строку для текущего языка пользователя по мнемонике (ключу).
     * <p>
     * Поиск выполняется автоматически для текущей локали. Если перевод не найден,
     * происходит авто-фолбэк на ресурс по умолчанию, а при его отсутствии — возвращается сам ключ.
     * </p>
     * 
     * @param mnemonic относительный ключ мнемоники (без префикса компонента)
     * @return локализованная строка или сам ключ при отсутствии перевода
     */
    String localize(String mnemonic);

    /**
     * Возвращает строку из ресурса по умолчанию (default/fallback) по ключу без префикса.
     * <p>
     * Используется, когда клиентскому коду нужно принудительно получить именно дефолтный 
     * (например, системный/русский) текст, даже если у пользователя выбран другой язык 
     * (например, для технических логов или аудита).
     * </p>
     * <p>
     * По умолчанию делегирует вызов в {@link #localize(String)}. Конкретные реализации могут
     * переопределять этот метод при наличии выделенного словаря дефолтных текстов.
     * </p>
     * 
     * @param mnemonic относительный ключ мнемоники
     * @return строка по умолчанию из дефолтного словаря
     */
    default String localizeDefault(String mnemonic) {
        return localize(mnemonic);
    }
}
